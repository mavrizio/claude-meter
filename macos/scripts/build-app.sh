#!/bin/bash
# Builds "build/Claude Meter.app": the menu bar app plus the statusLine helper for Claude Code.
# Usage: scripts/build-app.sh [release|debug]
# Ad-hoc signature by default (enough on this Mac). For distribution:
#   APP_DIR=folder        where to create the app (default: build)
#   UNIVERSAL=1           Apple Silicon + Intel
#   SIGN_ID="Developer ID Application: ..."   Developer ID signature, hardened runtime, timestamp
set -euo pipefail
cd "$(dirname "$0")/.."

CONFIG="${1:-release}"
ARCHS=()
[ "${UNIVERSAL:-0}" = 1 ] && ARCHS=(--arch arm64 --arch x86_64)
swift build -c "$CONFIG" ${ARCHS[@]+"${ARCHS[@]}"} --product ClaudeMeterApp
swift build -c "$CONFIG" ${ARCHS[@]+"${ARCHS[@]}"} --product claude-meter-statusline
BIN="$(swift build -c "$CONFIG" ${ARCHS[@]+"${ARCHS[@]}"} --show-bin-path)"

# Version: single source in Sources/MeterCore/Version.swift.
VERSION=$(sed -n 's/.*marketing = "\(.*\)".*/\1/p' Sources/MeterCore/Version.swift)
BUILD=$(sed -n 's/.*build = "\(.*\)".*/\1/p' Sources/MeterCore/Version.swift)
[ -n "$VERSION" ] && [ -n "$BUILD" ] || { echo "versione non trovata in Version.swift" >&2; exit 1; }
YEAR=$(date +%Y)

APP="${APP_DIR:-build}/Claude Meter.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN/ClaudeMeterApp" "$APP/Contents/MacOS/ClaudeMeter"
cp "$BIN/claude-meter-statusline" "$APP/Contents/MacOS/claude-meter-statusline"

# Icon: generated by scripts/make-icon.swift, only when missing or the script is newer.
ICON="Resources/AppIcon.icns"
if [ ! -f "$ICON" ] || [ scripts/make-icon.swift -nt "$ICON" ]; then
    mkdir -p Resources
    ICONSET="$(mktemp -d)/AppIcon.iconset"
    swift scripts/make-icon.swift "$ICONSET"
    iconutil -c icns "$ICONSET" -o "$ICON"
fi
cp "$ICON" "$APP/Contents/Resources/AppIcon.icns"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>Claude Meter</string>
    <key>CFBundleDisplayName</key><string>Claude Meter</string>
    <key>CFBundleIdentifier</key><string>com.mavrizio.claudemeter</string>
    <key>CFBundleExecutable</key><string>ClaudeMeter</string>
    <key>CFBundleIconFile</key><string>AppIcon</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>$VERSION</string>
    <key>CFBundleVersion</key><string>$BUILD</string>
    <key>CFBundleDevelopmentRegion</key><string>it</string>
    <key>NSHumanReadableCopyright</key><string>© $YEAR Maurizio Tolfa</string>
    <key>LSMinimumSystemVersion</key><string>14.0</string>
    <key>LSApplicationCategoryType</key><string>public.app-category.developer-tools</string>
    <key>LSUIElement</key><true/>
    <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

if [ -n "${SIGN_ID:-}" ]; then
    # Inner executable first, then the bundle (no --deep: Apple advises against it for signing).
    for target in "$APP/Contents/MacOS/claude-meter-statusline" "$APP"; do
        codesign --force --options runtime --timestamp --sign "$SIGN_ID" "$target"
    done
    codesign --verify --deep --strict "$APP"
else
    codesign --force --deep --sign - "$APP" >/dev/null
fi
echo "Creata: $APP  (versione $VERSION, build $BUILD)"
